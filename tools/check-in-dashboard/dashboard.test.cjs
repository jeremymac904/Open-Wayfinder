const assert=require('node:assert/strict'), d=require('./dashboard-core.js');
const base={date:'2026-11-16',mood:'7',energy:'',stress:'3',connection:'5',confidence:'8',note:'A good day'};
const e=d.makeEntry(base);
assert.equal(e.energy,null);
assert.equal(e.stress,3);
assert.throws(()=>d.makeEntry({...base,mood:'0'}));
assert.throws(()=>d.makeEntry({...base,date:'2026-02-30'}));
assert.throws(()=>d.makeEntry({...base,mood:'abc'}));
assert.throws(()=>d.readExport('{"version":1,"entries":[{"date":"bad"}]}'));
assert.deepEqual(d.readExport(d.exportData([e])).entries,[e]);
const data=[e,d.makeEntry({...base,date:'2026-11-15',mood:'5',stress:'9'}),d.makeEntry({...base,date:'2026-11-01',mood:'1'})];
const report=d.summary(data,'2026-11-16',7);
assert.equal(report.days,2);
assert.equal(report.mood.mean,6);
assert.equal(report.energy.mean,null);
assert.equal(report.stress.mean,6);
assert.equal(d.summary(data,'2026-11-16',14).days,2);
assert.equal(d.summary(data,'2026-11-16',30).days,3);
console.log('Check-in validation, missing values, export, date windows and stress checks passed');
